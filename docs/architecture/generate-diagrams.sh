#!/bin/sh
# Rewrites docs/architecture/diagrams.md from the LikeC4 model in docs/architecture/c4.
# The result renders on GitHub and in any Markdown viewer that supports Mermaid.
#
# Usage:   sh docs/architecture/generate-diagrams.sh
# Override the LikeC4 command with LIKEC4, for example: LIKEC4="./node_modules/.bin/likec4"
set -eu

cd "$(dirname "$0")"
LIKEC4="${LIKEC4:-npx --yes likec4}"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

$LIKEC4 codegen mermaid -o "$tmp" c4

{
  echo "# C4 diagrams"
  echo
  echo "> Generated from \`c4/*.c4\` by \`generate-diagrams.sh\`. Do not edit this file. Edit the model and run the script again."
  echo
  echo "> The elements \"Mod sources\" and \"Edge proxy\" are tagged \`planned\` in the model. They are not built yet. Mermaid does not show the tag. Use \`npx likec4 start\` to see it."
  echo
  for view in index containers apiComponents archiverComponents archiveRun queryCacheMiss queryCacheHit production; do
    title="$(sed -n 's/^title: "\(.*\)"$/\1/p' "$tmp/$view.mmd" | head -n 1)"
    echo "## ${title:-$view}"
    echo
    echo "View: \`$view\`"
    echo
    echo '```mermaid'
    cat "$tmp/$view.mmd"
    echo '```'
    echo
  done
} > diagrams.md

echo "Wrote $(pwd)/diagrams.md"
